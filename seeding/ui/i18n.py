def tr(language: str, key: str, fallback: str = "") -> str:
    """Возвращает перевод по ключу и языку."""
    locale = TRANSLATIONS.get(language) or TRANSLATIONS["ru"]
    if key in locale:
        return locale[key]
    if fallback:
        return fallback
    return key
